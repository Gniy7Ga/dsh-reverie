/**
 * Collect the license of every npm package esbuild bundled into lib/ and
 * render THIRD_PARTY_LICENSES.md. Packages are found from the build
 * metafiles, so the list always matches what actually ships.
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const LICENSE_FILE = /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i;

/** Directory of the package that owns a bundled input path (`.../node_modules/<name>/...`). */
function packageDirOf(root, input) {
  const absolute = resolve(root, input);
  const marker = '/node_modules/';
  const at = absolute.lastIndexOf(marker);
  if (at < 0) return undefined;
  const rest = absolute.slice(at + marker.length).split('/');
  const depth = rest[0].startsWith('@') ? 2 : 1;
  return absolute.slice(0, at + marker.length) + rest.slice(0, depth).join('/');
}

function repositoryUrl(manifest) {
  const repo = typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url;
  if (!repo) return manifest.homepage;
  return repo
    .replace(/^git\+/, '')
    .replace(/\.git$/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^github:/, 'https://github.com/')
    .replace(/^([\w.-]+\/[\w.-]+)$/, 'https://github.com/$1');
}

export function thirdPartyNotices(root, metafiles) {
  const dirs = new Set();
  for (const metafile of metafiles) {
    for (const input of Object.keys(metafile.inputs)) {
      const dir = packageDirOf(root, input);
      if (dir) dirs.add(dir);
    }
  }
  const packages = [...dirs].map((dir) => {
    const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const file = readdirSync(dir).find((name) => LICENSE_FILE.test(name));
    if (!file) throw new Error(`third-party-licenses: ${manifest.name} ships no license file`);
    return { name: manifest.name, version: manifest.version, license: manifest.license, url: repositoryUrl(manifest), text: readFileSync(join(dir, file), 'utf8').trim() };
  }).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));

  const lines = [
    '# Third-party licenses',
    '',
    '<!-- Generated by scripts/third-party-licenses.mjs during `npm run build`; do not edit by hand. -->',
    '',
    'The built files in `lib/` bundle the npm packages below. Each keeps its own license, reproduced in full.',
    'Code adapted from qiaomu-rss-dsh, Lucide icon paths and the react-tweet token formula are described in [NOTICE.md](NOTICE.md).',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...packages.map((p) => `| [${p.name}](${p.url ?? `https://www.npmjs.com/package/${p.name}`}) | ${p.version} | ${p.license} |`),
    '',
  ];
  for (const p of packages) lines.push(`## ${p.name}@${p.version}`, '', `License: ${p.license}${p.url ? ` · ${p.url}` : ''}`, '', '```text', p.text, '```', '');
  return `${lines.join('\n').trimEnd()}\n`;
}
